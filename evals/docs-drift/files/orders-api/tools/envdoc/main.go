// Command envdoc prints docs/config.md: every environment variable
// cmd/api/main.go reads, with the line that reads it. Run it through
// `make config-doc`; the output is committed and never edited by hand.
package main

import (
	"bufio"
	"fmt"
	"log"
	"os"
	"regexp"
)

const source = "cmd/api/main.go"

var getenv = regexp.MustCompile(`os\.Getenv\("([A-Z0-9_]+)"\)`)

func main() {
	f, err := os.Open(source)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	fmt.Println("<!-- Generated by `make config-doc` from cmd/api/main.go. Do not edit by hand. -->")
	fmt.Println("# Configuration")
	fmt.Println()
	fmt.Println("| Variable | Read at |")
	fmt.Println("| --- | --- |")
	seen := map[string]bool{}
	n := 0
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		n++
		for _, m := range getenv.FindAllStringSubmatch(sc.Text(), -1) {
			if seen[m[1]] {
				continue
			}
			seen[m[1]] = true
			fmt.Printf("| `%s` | %s:%d |\n", m[1], source, n)
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
}
