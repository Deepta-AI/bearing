#!/usr/bin/env node
// design-registry: write src/design/screens.generated.ts, the list of every
// screen design (src/features/<feature>/screens/*.screen.tsx) and every
// design direction (src/design/variants/<n>-<name>.css) the gallery shows.
// Next.js has no import.meta.glob, so the registry is generated; `--check`
// fails when the committed file is stale (make check runs it).
//
//   node scripts/design-registry.mjs          write the registry
//   node scripts/design-registry.mjs --check  exit 1 when it is out of date
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const out = join(root, "src/design/screens.generated.ts");

function screenFiles() {
  const features = join(root, "src/features");
  if (!existsSync(features)) return [];
  const files = [];
  for (const feature of readdirSync(features).sort()) {
    const dir = join(features, feature, "screens");
    if (!existsSync(dir)) continue;
    for (const f of readdirSync(dir).sort()) {
      if (f.endsWith(".screen.tsx")) files.push(`@/features/${feature}/screens/${f.slice(0, -4)}`);
    }
  }
  return files;
}

function variantFiles() {
  const dir = join(root, "src/design/variants");
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => /^[0-9]+-[a-z0-9-]+\.css$/.test(f))
    .sort();
}

const screens = screenFiles();
const variants = variantFiles();
const lines = [
  "// Generated by scripts/design-registry.mjs; do not edit. Run `make design-registry`.",
  'import type { ScreenModule } from "./screen";',
  ...screens.map((s, i) => `import * as screen${i} from "${s}";`),
  ...variants.map((v) => `import "./variants/${v}";`),
  "",
  `export const screenModules: ScreenModule[] = [${screens.map((_, i) => `screen${i}`).join(", ")}];`,
  `export const variantNames: string[] = [${variants.map((v) => JSON.stringify(v.slice(0, -4))).join(", ")}];`,
  "",
];
const text = lines.join("\n");

if (process.argv.includes("--check")) {
  if (screens.length === 0) {
    console.error("design-registry: 0 screen files under src/features/*/screens, nothing checked");
    process.exit(1);
  }
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current !== text) {
    console.error(
      `design-registry: src/design/screens.generated.ts is stale (${screens.length} screens, ${variants.length} variants on disk); run make design-registry`,
    );
    process.exit(1);
  }
  console.log(`design-registry: ${screens.length} screens, ${variants.length} variants checked`);
} else {
  writeFileSync(out, text);
  console.log(`design-registry: ${screens.length} screens, ${variants.length} variants written`);
}
