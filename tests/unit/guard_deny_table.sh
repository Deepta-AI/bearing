rows=0; denies=0; allows=0
t_begin "table"
while IFS="$(printf '\t')" read -r expect cmd; do
  rows=$((rows+1))
  case "$expect" in DENY) want=2; denies=$((denies+1));; ALLOW) want=0; allows=$((allows+1));; *) _t_fail "bad row: $expect"; continue;; esac
  assert_exit "$want" bash "$GUARD" command "$cmd"
  if [ "$want" -eq 2 ]; then assert_eq 1 "$(printf '%s' "$T_OUT" | grep -qE 'Bearing blocked|brg-guard:' && echo 1)" "deny message names the guard for [$cmd]"; else assert_eq "" "$T_OUT" "allow prints nothing for [$cmd]"; fi
done < "$table"
t_end

